package com.moon.bianliang;

public class Test02 {
    /**
     * 字面量
     * @param args
     */
    public static void main(String[] args) {
        System.out.println("moon"); // 字符串(使用双引号包裹)
        System.out.println(18); // 整数
        System.out.println(180.1); // 浮点数
        System.out.println('男'); // 字符(使用单引号包裹,里面有且仅有一个字符)
        System.out.println(false); // 布尔(只有两个值true/false)
    }
}
