package com.moon.bianliang;

public class Test03 {
    /**
     * 变量
     * 定义: 数据类型 变量名 = 数据值
     * @param args
     */
    public static void main(String[] args) {
        int num =10; // 定义一个整形变量num,值为10
        int age=18; // 定义一个整形变量age,值为18
        System.out.println(age); // 打印变量
        age=20; // 修改变量
        System.out.println(age+10); // 计算
    }
}
