package com.moon.bianliang;

public class Test06 {
    /**
     * 数据类型(基本/引用类型)
     *
     * @param args
     */
    public static void main(String[] args) {
        /*
        基本类型(8种):
            整形:
                    byte    1bytes
                    short   2bytes
                    int     4bytes
                    long    8bytes
            浮点型:
                    float  单精度 4bytes
                    double 双精度 8bytes
            布尔型:  boolean    1bytes
            字符型:  char       2bytes
         */

        // 整形默认是int,如果使用long,后面需要加入l/L
        long tel=18088889999l; // 尽量使用L,l容易被当成1
        long tel1=18088889999L;

        // 浮点型默认是double,如果使用float,后面需要加入f/F
        float f1=3.14f;
        float f2=3.14F;



    }
}
