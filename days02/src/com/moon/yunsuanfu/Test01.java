package com.moon.yunsuanfu;

public class Test01 {
    /**
     * 算数运算符
     * @param args
     */
    public static void main(String[] args) {
        /*
        + - * / %
        / 是两数除法运算的商(只有浮点数参与运算,结果才是浮点数)
        % 是两数除法运算的余数
         */
        int num1=10;
        int num2=20;
        System.out.println(num1+num2);
        System.out.println(num1-num2);
        System.out.println(num1*num2);
        System.out.println(num2/num1);
        System.out.println(num2%num1);
    }
}
