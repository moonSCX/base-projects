package com.moon.yunsuanfu;

public class Test08 {
    /**
     * 关系运算符
     * @param args
     */
    public static void main(String[] args) {
        /*
        > >= < <= == !=
         */
        System.out.println(10>20);
        System.out.println(10>=20);
        System.out.println(10<20);
        System.out.println(10<=20);
        System.out.println(10==20);
        System.out.println(10!=20);
    }
}
